#!/usr/bin/env python3
"""Compile the shader sources in ``scripts/shaders`` into MoonBit byte strings.

The Vulkan backend takes SPIR-V, and the shaders the examples and the tests use
have to be in the repository in a form a program can hand to
``ShaderModuleDescriptor::spirv``. This script is that form's generator: it runs
``glslangValidator`` over each source and writes the words into
``src/shaders/modules.mbt``.

The wrapper's shader compiler produces the same SPIR-V from WGSL; until it is
linked, these modules are the shaders a backend can be given.
"""

import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "scripts" / "shaders"
OUTPUT = ROOT / "src" / "shaders" / "modules.mbt"

MODULES = [
    ("triangle.vert", "vert", "triangle_vertex"),
    ("triangle.frag", "frag", "triangle_fragment"),
    ("texture.vert", "vert", "texture_vertex"),
    ("texture.frag", "frag", "texture_fragment"),
    ("fill.comp", "comp", "fill_compute"),
]

HEADER = """// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by `scripts/build_shaders.py` from `scripts/shaders`. These are the
// SPIR-V words of each module; regenerate rather than edit.
"""


def escape(data: bytes) -> str:
    out = []
    for byte in data:
        if 32 <= byte < 127 and byte not in (0x22, 0x5C):
            out.append(chr(byte))
        else:
            out.append("\\x%02x" % byte)
    return "".join(out)


def compile_one(tool: str, source: pathlib.Path, stage: str, target: pathlib.Path) -> bytes:
    command = [
        tool,
        "-V",
        "--target-env",
        "vulkan1.3",
        "-S",
        stage,
        str(source),
        "-o",
        str(target),
    ]
    subprocess.run(command, check=True, capture_output=True)
    return target.read_bytes()


def main() -> int:
    tool = shutil.which("glslangValidator") or shutil.which("glslc")
    if not tool:
        print("no glslangValidator or glslc on PATH", file=sys.stderr)
        return 1
    body = [HEADER]
    with tempfile.TemporaryDirectory() as work:
        for name, stage, symbol in MODULES:
            source = SOURCES / name
            if not source.exists():
                print("missing %s" % source, file=sys.stderr)
                return 1
            words = compile_one(tool, source, stage, pathlib.Path(work) / (name + ".spv"))
            if len(words) % 4 != 0:
                print("%s did not produce whole words" % name, file=sys.stderr)
                return 1
            body.append("///|\n/// The module `%s` compiles to.\n" % name)
            body.append('pub let %s : Bytes = b"%s"\n' % (symbol, escape(words)))
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print("wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
