"""Compile the MoonBit code in the README and in docs/skills.

Every fenced block tagged `moonbit check` has to compile; blocks tagged
`moonbit nocheck` are examples in another language, or fragments, and are left
alone. The blocks of one file are concatenated in order, so a later block can
use a name an earlier one introduced.

The check runs as a throwaway package inside this module, so the imports are the
real ones and `moon check --deny-warn` sees exactly what a reader would.
"""

from __future__ import annotations

import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FENCE = re.compile(r"```moonbit([^\n]*)\n(.*?)```", re.S)
PACKAGE = ROOT / "src" / "doc_snippets"

IMPORTS = """// Generated by scripts/check_snippets.py: not part of the library.
pkgtype(kind: "library")

import {
  "moonbitstack/moonwgpu",
  "moonbitstack/moonwgpu/types" @types,
  "moonbitstack/moonwgpu/core" @core,
  "moonbitstack/moonwgpu/hal/memory" @memory,
}
"""


def documents() -> list[pathlib.Path]:
    found = [ROOT / "README.md"]
    skills = ROOT / "docs" / "skills"
    if skills.is_dir():
        found.extend(sorted(skills.glob("*/SKILL.md")))
    return [path for path in found if path.is_file()]


def blocks(text: str) -> list[str]:
    checked = []
    for tags, body in FENCE.findall(text):
        if "nocheck" in tags:
            continue
        checked.append(body)
    return checked


def main() -> int:
    sources = []
    for document in documents():
        for index, body in enumerate(blocks(document.read_text(encoding="utf-8"))):
            name = document.stem.replace("-", "_")
            sources.append(f"///|\n/// From {document.name}, block {index + 1}.\n")
            for line in body.rstrip().splitlines():
                sources.append(line + "\n")
            sources.append("\n")
    if not sources:
        print("no checked blocks")
        return 0
    PACKAGE.mkdir(parents=True, exist_ok=True)
    (PACKAGE / "moon.pkg").write_text(IMPORTS, encoding="utf-8")
    (PACKAGE / "snippets.mbt").write_text("".join(sources), encoding="utf-8")
    try:
        result = subprocess.run(
            ["moon", "check", "--deny-warn"],
            cwd=ROOT,
            text=True,
        )
    finally:
        shutil.rmtree(PACKAGE, ignore_errors=True)
    if result.returncode != 0:
        print("the code in the docs does not compile", file=sys.stderr)
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
