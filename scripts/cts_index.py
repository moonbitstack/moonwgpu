#!/usr/bin/env python3
"""Index the WebGPU conformance suite: every test file, every case name.

The suite cannot be executed against this library - it drives `navigator.gpu`
from TypeScript, and this package is MoonBit over its own `hal` - so the useful
thing to import is its shape: which files test which rules, and which cases each
file declares. This script reads the checked-out `cts/` submodule and writes
`conformance/cts-cases.txt`, which is committed, so a review can see a case
disappear without cloning anything.

Usage:
  python3 scripts/cts_index.py           # rewrite conformance/cts-cases.txt
  python3 scripts/cts_index.py --check   # fail if the file is stale
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CTS = ROOT / "cts"
OUT = ROOT / "conformance" / "cts-cases.txt"

# `g.test('name'` and `g.test(\n    "name"` are the two spellings in the suite.
CASE = re.compile(r"\.test\(\s*['\"]([^'\"]+)['\"]")


def cts_revision() -> str:
    try:
        return subprocess.run(
            ["git", "-C", str(CTS), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"


def index() -> list[str]:
    if not (CTS / "src" / "webgpu").is_dir():
        sys.exit(
            "cts/src/webgpu is missing: run "
            "`git submodule update --init --depth 1 cts` and narrow it with "
            "`git -C cts sparse-checkout set --cone src/webgpu`"
        )
    rows = []
    for path in sorted((CTS / "src" / "webgpu").rglob("*.spec.ts")):
        rel = path.relative_to(CTS).as_posix()
        text = path.read_text(encoding="utf-8")
        for name in CASE.findall(text):
            rows.append(f"{rel}\t{name}")
    return sorted(set(rows))


def render(rows: list[str]) -> str:
    head = [
        "# Generated by scripts/cts_index.py from the cts/ submodule.",
        "# suite: gpuweb/cts",
        "# revision: " + cts_revision(),
        "# columns: file<TAB>case",
        f"# cases: {len(rows)}",
        "",
    ]
    return "\n".join(head + rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if stale")
    args = parser.parse_args()

    rows = index()
    body = render(rows)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != body:
            sys.stderr.write(
                "conformance/cts-cases.txt is stale: run scripts/cts_index.py\n"
            )
            return 1
        print(f"cts index is current: {len(rows)} cases")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
